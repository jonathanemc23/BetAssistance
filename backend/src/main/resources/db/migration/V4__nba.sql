-- NBA Intelligence (phase 1): the statistics engine's own schema. The
-- Python engine in nba/ writes here; the server only reads. Nothing here
-- touches the community tables or the bankroll, which stays on the phone.
--
-- Time rules: every row says when its information became available
-- (available_at) and when we fetched it (fetched_at), so a backtest never
-- uses data it couldn't have had. Predictions are insert-only.
--
-- Kept to SQL that H2's PostgreSQL mode also runs (the server's tests):
-- JSON goes in text columns.

create schema if not exists nba;

-- Every provider response as it came, never edited (the original history).
create table nba.raw_payloads (
    id           bigint generated by default as identity primary key,
    source       varchar(40)  not null,
    kind         varchar(40)  not null,            -- scoreboard, summary, ...
    source_key   varchar(120) not null,            -- date or game id at the source
    url          varchar(500) not null,
    sha256       varchar(64)  not null,
    body         text         not null,
    fetched_at   timestamp with time zone not null,
    unique (source, kind, source_key, sha256)
);

-- Import problems: missing fields, impossible stats, duplicates.
create table nba.import_log (
    id          bigint generated by default as identity primary key,
    run_id      varchar(64)  not null,
    level       varchar(10)  not null,              -- info, warning, error
    source      varchar(40)  not null,
    source_key  varchar(120),
    message     varchar(1000) not null,
    created_at  timestamp with time zone not null
);

-- Our own ids for teams, players and games, never a provider's: models and
-- predictions only see these, so changing provider means adding rows to
-- nba.external_ids, not rebuilding anything.
create table nba.teams (
    team_id      varchar(40) primary key,          -- e.g. t_lal
    abbreviation varchar(10) not null,
    name         varchar(80) not null
);

create table nba.players (
    player_id   varchar(40) primary key,           -- e.g. p_000123
    name        varchar(120) not null,
    position    varchar(10),
    birth_date  date,                               -- helps match players across providers
    active      boolean not null default true,
    first_seen  date,
    last_seen   date
);

-- Each provider's id for one of ours. A new provider adds rows here.
create table nba.external_ids (
    entity      varchar(10)  not null,              -- team, player, game
    source      varchar(40)  not null,              -- espn, sportradar, ...
    source_id   varchar(60)  not null,
    internal_id varchar(40)  not null,
    linked_at   timestamp with time zone not null,
    link_method varchar(20)  not null,              -- created, exact, manual
    primary key (entity, source, source_id)
);
create index external_ids_internal on nba.external_ids (entity, internal_id);

-- Which team a player was on, and when (team changes).
create table nba.player_team_spells (
    player_id  varchar(40) not null references nba.players (player_id),
    team_id    varchar(40) not null references nba.teams (team_id),
    from_date  date not null,
    to_date    date,
    primary key (player_id, team_id, from_date)
);

create table nba.games (
    game_id      varchar(40) primary key,          -- e.g. g_20251120_lac_orl
    season       integer     not null,             -- 2026 = the 2025-26 season
    season_type  varchar(20) not null,             -- regular, playoffs, ...
    home_team_id varchar(40) not null references nba.teams (team_id),
    away_team_id varchar(40) not null references nba.teams (team_id),
    tipoff_at    timestamp with time zone not null,
    status       varchar(20) not null,             -- scheduled, live, final, postponed
    home_score   integer,
    away_score   integer,
    final_at     timestamp with time zone,         -- when the result was known
    source       varchar(40) not null,             -- provider the row came from
    fetched_at   timestamp with time zone not null
);
create index games_tipoff on nba.games (tipoff_at);

-- One player's line in one game. Null = not recorded; 0 = recorded as zero.
create table nba.player_games (
    game_id       varchar(40) not null references nba.games (game_id),
    player_id     varchar(40) not null references nba.players (player_id),
    team_id       varchar(40) not null references nba.teams (team_id),
    opponent_id   varchar(40) not null references nba.teams (team_id),
    home          boolean not null,
    starter       boolean not null,
    did_not_play  boolean not null,
    dnp_reason    varchar(120),
    minutes       double precision,
    points        integer,
    rebounds      integer,
    oreb          integer,
    dreb          integer,
    assists       integer,
    fgm integer, fga integer, tpm integer, tpa integer, ftm integer, fta integer,
    turnovers     integer,
    steals        integer,
    blocks        integer,
    fouls         integer,
    plus_minus    integer,
    flags         varchar(200) not null default '',  -- comma list: odd_minutes, impossible, ...
    available_at  timestamp with time zone not null, -- the game's final_at
    source        varchar(40) not null,
    fetched_at    timestamp with time zone not null,
    primary key (game_id, player_id)
);
create index player_games_player on nba.player_games (player_id, available_at);

-- Team totals per game, with estimated possessions (pace and ratings).
create table nba.team_games (
    game_id      varchar(40) not null references nba.games (game_id),
    team_id      varchar(40) not null references nba.teams (team_id),
    opponent_id  varchar(40) not null references nba.teams (team_id),
    home         boolean not null,
    minutes      double precision,
    points       integer, rebounds integer, oreb integer, dreb integer, assists integer,
    fgm integer, fga integer, tpm integer, tpa integer, ftm integer, fta integer,
    turnovers    integer,
    possessions  double precision,
    available_at timestamp with time zone not null,
    primary key (game_id, team_id)
);

-- Availability entered by hand (phase 1) or, later, by a news feed. Insert-
-- only: a new report supersedes the old one from its reported_at, and a
-- prediction uses the latest report made before it (no hindsight).
create table nba.player_availability (
    id           bigint generated by default as identity primary key,
    player_id    varchar(40) not null references nba.players (player_id),
    game_id      varchar(40) not null references nba.games (game_id),
    status       varchar(20) not null,              -- available, questionable, out, restricted
    minutes_cap  double precision,                  -- with restricted (or any status): most minutes expected
    play_probability double precision,              -- optional override for questionable, 0..1
    note         varchar(500) not null default '',
    source       varchar(40) not null,              -- manual, ...
    entered_by   varchar(128),                      -- user id for manual entries
    reported_at  timestamp with time zone not null,
    check (status in ('available', 'questionable', 'out', 'restricted')),
    check (minutes_cap is null or (minutes_cap >= 0 and minutes_cap <= 60)),
    check (play_probability is null or (play_probability >= 0 and play_probability <= 1))
);
create index availability_game on nba.player_availability (game_id, player_id, reported_at);

-- Engine features for one player before one game, built only from earlier games.
create table nba.features (
    player_id           varchar(40) not null references nba.players (player_id),
    game_id             varchar(40) not null references nba.games (game_id),
    feature_set_version varchar(20) not null,
    as_of               timestamp with time zone not null, -- latest information used
    values_json         text not null,
    created_at          timestamp with time zone not null,
    primary key (player_id, game_id, feature_set_version)
);

-- Every trained model, by name and version.
create table nba.models (
    name         varchar(60) not null,              -- minutes, points, rebounds, assists
    version      varchar(40) not null,
    family       varchar(40) not null,              -- baseline, ridge, lightgbm, ...
    params_json  text not null,
    code_hash    varchar(64) not null,
    trained_to   timestamp with time zone,          -- last game in its training data
    trained_at   timestamp with time zone not null,
    status       varchar(20) not null,              -- candidate, production, retired
    notes        varchar(1000) not null default '',
    primary key (name, version)
);

-- One prediction per player, game and market. Insert-only.
create table nba.predictions (
    id                  bigint generated by default as identity primary key,
    player_id           varchar(40) not null references nba.players (player_id),
    game_id             varchar(40) not null references nba.games (game_id),
    market              varchar(20) not null,       -- minutes, points, rebounds, assists
    model_name          varchar(60) not null,
    model_version       varchar(40) not null,
    predicted_at        timestamp with time zone not null, -- before tip-off
    as_of               timestamp with time zone not null, -- latest information used
    mean                double precision not null,
    median              double precision not null,
    p10                 double precision,
    p90                 double precision,
    distribution        varchar(40) not null,       -- poisson, negbin, empirical, mixture, normal
    dist_params_json    text not null,
    pmf_json            text,                       -- P(X = k), k = 0..n
    features_json       text not null,              -- the variables available
    data_quality        varchar(10) not null,       -- high, medium, low
    availability_id     bigint references nba.player_availability (id), -- the report used, if any
    play_probability    double precision not null default 1, -- P(the player plays) used
    run_id              varchar(64) not null,
    backtest            boolean not null default false,
    foreign key (model_name, model_version) references nba.models (name, version)
);
create index predictions_game on nba.predictions (game_id, market);
create index predictions_player on nba.predictions (player_id, market, predicted_at);

create table nba.backtest_runs (
    run_id        varchar(64) primary key,
    model_name    varchar(60) not null,
    model_version varchar(40) not null,
    from_date     date not null,
    to_date       date not null,
    window_days   integer not null,
    started_at    timestamp with time zone not null,
    finished_at   timestamp with time zone,
    status        varchar(20) not null,
    config_json   text not null
);

-- One metric for one slice of a run: market, season, starter, minutes range, ...
create table nba.backtest_metrics (
    run_id       varchar(64)  not null references nba.backtest_runs (run_id),
    market       varchar(20)  not null,
    slice        varchar(60)  not null,             -- all, season=2025, starter=true, ...
    metric       varchar(30)  not null,             -- mae, rmse, brier, log_loss, ece, ...
    metric_value double precision not null,
    ci_low       double precision,                  -- 95% interval (block bootstrap by date)
    ci_high      double precision,
    n            integer not null,
    primary key (run_id, market, slice, metric)
);

-- A pipeline run: when the data was last brought up to date.
create table nba.pipeline_runs (
    run_id       varchar(64) primary key,
    kind         varchar(30) not null,              -- ingest, features, predict, backtest
    started_at   timestamp with time zone not null,
    finished_at  timestamp with time zone,
    status       varchar(20) not null,              -- running, ok, failed
    summary_json text not null default '{}'
);
