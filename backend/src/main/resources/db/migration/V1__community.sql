-- The community: profiles and follows, bets (free, for sale, challenge),
-- purchases, the token ledger and the pro bettor challenge.

create table profiles (
    user_id    varchar(128) primary key,
    handle     varchar(20)  not null unique,
    name       varchar(80)  not null,
    bio        varchar(120) not null default '',
    avatar     varchar(200) not null default '',
    joined_at  timestamp with time zone not null
);

create table follows (
    follower_id varchar(128) not null references profiles (user_id),
    followed_id varchar(128) not null references profiles (user_id),
    created_at  timestamp with time zone not null,
    primary key (follower_id, followed_id)
);

create table challenges (
    user_id    varchar(128) primary key references profiles (user_id),
    attempt    integer not null default 0,
    started_at timestamp with time zone,
    wait_until timestamp with time zone,
    passed_at  timestamp with time zone,
    last_rate  double precision
);

create table bets (
    id          bigint generated by default as identity primary key,
    owner_id    varchar(128) not null references profiles (user_id),
    kind        varchar(12)  not null, -- FREE, SALE, CHALLENGE
    attempt     integer,               -- the challenge attempt, for CHALLENGE bets
    match_id    varchar(40)  not null,
    league      varchar(40)  not null,
    home        varchar(80)  not null,
    away        varchar(80)  not null,
    kickoff     timestamp with time zone not null,
    market      varchar(20)  not null,
    pick        varchar(120) not null,
    line        double precision,
    odds        double precision not null,
    price       integer not null default 0,
    result      varchar(4),            -- WON, LOST, or null until settled
    created_at  timestamp with time zone not null
);
create index bets_feed on bets (kind, kickoff);
create index bets_open on bets (result, kickoff);
create index bets_owner on bets (owner_id, kind);

create table purchases (
    buyer_id   varchar(128) not null references profiles (user_id),
    bet_id     bigint not null references bets (id),
    price      integer not null,
    created_at timestamp with time zone not null,
    primary key (buyer_id, bet_id)
);

-- Every token movement; a user's balance is the sum of their rows.
create table token_entries (
    id         bigint generated by default as identity primary key,
    user_id    varchar(128) not null,
    amount     integer not null,
    reason     varchar(40) not null, -- WELCOME, PURCHASE, BUY_BET, SALE, PLAY_STORE
    reference  varchar(200),
    created_at timestamp with time zone not null
);
create index token_entries_user on token_entries (user_id);
create unique index token_entries_reference on token_entries (reason, reference);
