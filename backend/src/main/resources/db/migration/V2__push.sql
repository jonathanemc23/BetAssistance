-- Web Push: the server's key pair, the phones that get live alerts with the
-- app closed, and the matches each phone follows.

create table push_keys (
    id          integer primary key,
    public_key  varchar(100) not null,
    private_key varchar(400) not null
);

create table push_devices (
    id         bigint generated by default as identity primary key,
    endpoint   varchar(1000) not null unique,
    p256dh     varchar(200)  not null,
    auth       varchar(100)  not null,
    lang       varchar(5)    not null default 'en',
    updated_at timestamp with time zone not null
);

-- One row per phone and match. state and the scores are what the last
-- reading saw, so the next one only alerts on what changed.
create table push_watches (
    id         bigint generated by default as identity primary key,
    device_id  bigint not null references push_devices (id) on delete cascade,
    match_id   varchar(64)   not null,
    feed       varchar(80)   not null,
    sport      varchar(20)   not null,
    kickoff    timestamp with time zone not null,
    home       varchar(80)   not null,
    away       varchar(80)   not null,
    picks      varchar(1000) not null default '',
    state      varchar(12),
    home_score varchar(8),
    away_score varchar(8),
    unique (device_id, match_id)
);

create index push_watches_kickoff on push_watches (kickoff);
